/* ============================================================
   Currency configuration per language.
   Rates are approximate fixed rates (informative display only).
   1 RSD ≈ values below:
   ============================================================ */
window.PPTZ_CURRENCY = {
  sr: { code: 'RSD', symbol: 'RSD',  rate: 1,        locale: 'sr-RS', decimals: 0,  position: 'after'  },
  en: { code: 'GBP', symbol: '£',    rate: 0.0085,   locale: 'en-GB', decimals: 2,  position: 'before' },
  hr: { code: 'EUR', symbol: '€',    rate: 0.0085,   locale: 'hr-HR', decimals: 2,  position: 'after'  },
  es: { code: 'EUR', symbol: '€',    rate: 0.0085,   locale: 'es-ES', decimals: 2,  position: 'after'  },
  de: { code: 'EUR', symbol: '€',    rate: 0.0085,   locale: 'de-DE', decimals: 2,  position: 'after'  },
};

/* Format a RSD number into the target currency string */
window.PPTZ_formatPrice = function(rsdAmount, lang) {
  var cfg = window.PPTZ_CURRENCY[lang] || window.PPTZ_CURRENCY['sr'];
  var converted = rsdAmount * cfg.rate;
  var formatted;
  if (cfg.decimals === 0) {
    formatted = Math.round(converted).toLocaleString(cfg.locale);
  } else {
    formatted = converted.toLocaleString(cfg.locale, {
      minimumFractionDigits: cfg.decimals,
      maximumFractionDigits: cfg.decimals
    });
  }
  return cfg.position === 'before'
    ? cfg.symbol + formatted
    : formatted + ' ' + cfg.code;
};

/* Update all [data-price-rsd] elements on the page */
window.PPTZ_applyPrices = function(lang) {
  document.querySelectorAll('[data-price-rsd]').forEach(function(el) {
    var rsd = parseFloat(el.getAttribute('data-price-rsd'));
    if (!isNaN(rsd)) {
      el.textContent = window.PPTZ_formatPrice(rsd, lang);
    }
  });
};


window.applyLang = function(lang) {
  var dict = window.PPTZ_I18N[lang];
  if (!dict) return;

  // Save to localStorage so it persists across page loads
  try { localStorage.setItem('pptz_lang', lang); } catch(e) {}

  // Update document language attribute
  document.documentElement.lang = lang;

  // 1. Handle [data-i18n-html] elements first (innerHTML) — e.g. hero h1 with <br>/<span>
  //    This replaces their inner content, so any nested [data-i18n] children are removed.
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  // 2. Apply translations to all [data-i18n] elements (text content only)
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    // Skip elements that are now inside a replaced data-i18n-html container
    if (el.closest('[data-i18n-html]')) return;
    var key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  // Update all price elements to show converted currency
  window.PPTZ_applyPrices(lang);

  // Update lang-toggle button to show selected flag + code
  var langMeta = {
    sr: { abbr: 'RS', flag: 'images/flags/rs.webp' },
    en: { abbr: 'GB', flag: 'images/flags/gb.webp' },
    hr: { abbr: 'HR', flag: 'images/flags/hr.webp' },
    es: { abbr: 'ES', flag: 'images/flags/es.webp' },
    de: { abbr: 'DE', flag: 'images/flags/de.webp' }
  };
  var meta = langMeta[lang];
  if (meta) {
    var toggle = document.querySelector('.lang-toggle');
    if (toggle) {
      // Replace the icon + text span content
      var spans = toggle.querySelectorAll('span');
      // spans[0] = text label "Lng"
      if (spans[0]) {
        spans[0].innerHTML =
          '<img src="' + meta.flag + '" alt="' + meta.abbr + '" style="width:18px;height:13px;object-fit:cover;border-radius:2px;vertical-align:middle;margin-right:4px;">' + meta.abbr;
      }
    }
    // Update active state in dropdown
    document.querySelectorAll('.lang-option').forEach(function(opt) {
      opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
    });
  }
};

/* Auto-apply on page load */
(function() {
  var saved;
  try { saved = localStorage.getItem('pptz_lang'); } catch(e) {}
  window.applyLang(saved || 'sr');
})();
